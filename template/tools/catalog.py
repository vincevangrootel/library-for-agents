#!/usr/bin/env python3
"""Regenerate CATALOG.md at the library root from each books/*/book.yaml and its overview. Run after any book changes.
  catalog.py [--root LIB]
"""
import argparse, glob, json, os, yaml

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--root', default='.')
    a = ap.parse_args()
    rows = []
    for p in sorted(glob.glob(os.path.join(a.root, 'books', '*', 'book.yaml'))):
        bd = os.path.dirname(p)
        cfg = yaml.safe_load(open(p))
        ov = os.path.join(bd, '03-enrich', 'book-overview.yaml')
        ov = yaml.safe_load(open(ov)) if os.path.exists(ov) else {}
        man = os.path.join(bd, '02-text', 'manifest.json')
        n = len([d for d in json.load(open(man))['documents'] if d['kind'] == 'chapter']) if os.path.exists(man) else 0
        st = cfg.get('status', {})
        rows.append((cfg, ov, n, st, os.path.basename(bd)))
    L = ['# Catalog', '', 'Generated by `tools/catalog.py`. Do not edit by hand.', '',
         '| Book | Author | Chapters | Status | Folder |', '|---|---|---|---|---|']
    for cfg, ov, n, st, slug in rows:
        s = ', '.join(k for k, v in st.items() if v) or 'new'
        L.append(f"| {cfg['title']} | {cfg['author']} | {n} | {s} | [books/{slug}](books/{slug}/CONTEXT.md) |")
    L.append('')
    for cfg, ov, n, st, slug in rows:
        L += [f"## {cfg['title']}", f"Author: {cfg['author']}. Folder: `books/{slug}/`. Start at `books/{slug}/04-assemble/INDEX.md`.", '']
        if ov.get('summary'):
            L += [ov['summary'].strip(), '']
        if ov.get('topics'):
            L += ['Topics: ' + ', '.join(ov['topics']), '']
    open(os.path.join(a.root, 'CATALOG.md'), 'w').write('\n'.join(L) + '\n')
    print(f'catalog: {len(rows)} books')

main()
